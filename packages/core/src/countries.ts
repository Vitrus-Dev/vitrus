// packages/core/src/countries.ts
// ISO-3166 alpha-2 → English name and an approximate centroid.
//
// Why this exists at all: the dashboard was printing raw country codes ("TR",
// "BR") in the audience table, and the globe needs somewhere to put a dot.
//
// Why a CENTROID and not a map: we resolve country from the proxy's header
// (see geo.ts) and nothing finer — no city, no region, because we do not bundle
// a GeoIP database. A country-level dot is therefore exactly as precise as the
// measurement behind it. Drawing a shaded country polygon would imply we know
// where inside the country the visit came from; we do not, and a visualisation
// that implies more precision than the data has is the same failure as a
// fabricated number.
//
// The coordinates are approximate — roughly the visual centre of the landmass,
// to about a degree. That is far below the resolution of a dot on a 600px
// globe, and the comment is here so nobody later mistakes this table for a
// geodetic reference and uses it for something it cannot support. For countries
// with scattered territories (France, Norway, the Netherlands) the value is the
// mainland, because that is what a reader expects to see light up.
//
// Codes absent from this table are NOT silently dropped by the globe: it counts
// them and says so. An unplottable country is a gap in this file, and the only
// way anyone finds out is if the page admits it.

