/** The country's English name, or the raw code when we do not know it. */
export function countryName(code: string): string {
  return COUNTRIES[code.toUpperCase()]?.name ?? code;
}

/** Centroid, or null when the code is not in the table. Callers must handle null. */
export function countryPoint(code: string): { lat: number; lon: number } | null {
  const c = COUNTRIES[code.toUpperCase()];
  return c ? { lat: c.lat, lon: c.lon } : null;
}
